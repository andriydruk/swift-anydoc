/// The table a font's `/Encoding` selects.
///
/// The argument is the name from `/Encoding`, or from `/BaseEncoding` when
/// `/Encoding` is a dictionary carrying `/Differences`. Anything unrecognised
/// — including no name at all — is `StandardEncoding`, which is both the
/// specification's default and what the reference was measured doing.
func pdfBaseEncodingTable(named name: String?) -> [UInt8: String] {
    switch name {
    case "WinAnsiEncoding": return pdfWinAnsiEncodingTable
    case "MacRomanEncoding": return pdfMacRomanEncodingTable
    default: return pdfStandardEncodingTable
    }
}
