/// The simple-font base encodings, measured from the reference.
///
/// A simple font's byte is not its character. `/Encoding` names one of these
/// tables, and **a font that names none is read as `StandardEncoding`** —
/// not as Latin-1, which is the mistake this file exists to correct. In
/// StandardEncoding `0xE9` is `\u{00D8}` and `0xB7` is a bullet, where
/// Latin-1 would say `\u{00E9}` and a middle dot; and 107 of the 256 codes
/// mean nothing at all and are dropped rather than rendered.
///
/// **These tables were derived by measurement, not transcription.** lopdf
/// stores each code as an index into a glyph-name table, and hand-copying
/// 768 entries through that indirection would introduce errors no test would
/// catch. Instead one PDF was generated per encoding per code — 1024 of
/// them — and the reference asked what each produced. What is written here
/// is therefore what the reference does, including where that differs from
/// the published Adobe tables.
///
/// Codes map to **strings**, not scalars: `0xAE` is `fi` in StandardEncoding
/// and `0xDE` is `fi` in MacRoman, ligatures that occupy one code and two
/// characters.

